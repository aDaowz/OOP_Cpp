#include "Calculadora.h"

int Calculadora::sumar(int a, int b)
{
    return a + b;
}

int Calculadora::sumar(int a, int b, int c)
{
    return a + b + c;
}

double Calculadora::sumar(double a, double b)
{
    return a + b;
}

double Calculadora::sumar(double a, double b, double c)
{
    return a + b + c;
}
